<h1>About this example</h1>

<p>The <strong>Cloude</strong> framework follows these principles:</p>

<ul>
    <li>No magic, no code generators, no service container.</li>
    <li>Small classes, static when it makes sense.</li>
    <li>PSR-4 namespace <code>Cloude\</code>.</li>
    <li>PHP 8.3+, strict types, PER-CS 2.0 / PSR-12 coding style.</li>
</ul>

<p>The goal is to learn by reading the source - nothing is hidden behind abstractions.</p>
